# Slicing extracts a portion of a string.

text = "Python Programming"

# Basic slicing
print(text[0:6])
print(text[7:18])

# Omitting start or end
print(text[:6])
print(text[7:])

# Copy a string
print(text[:])

# Step value
print(text[::2])

# Reverse a string
print(text[::-1])

# Last characters
print(text[-5:])