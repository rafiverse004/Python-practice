# Escape characters allow special characters inside strings.

# New line
print("Hello\nWorld")

# Tab
print("Name\tAge")

# Double quote
print("She said, \"Python is fun!\"")

# Single quote
print('It\'s a beautiful day.')

# Backslash
print("C:\\Users\\Rafik\\Documents")

# Raw string
path = r"C:\Users\Rafik\Documents"
print(path)