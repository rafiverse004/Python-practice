# Comparison operators compare two values and return True or False.

num1 = 10
num2 = 20

print("num1 == num2:", num1 == num2)
print("num1 != num2:", num1 != num2)
print("num1 > num2 :", num1 > num2)
print("num1 < num2 :", num1 < num2)
print("num1 >= num2:", num1 >= num2)
print("num1 <= num2:", num1 <= num2)

# Comparisons with strings
username = "admin"

print("\nIs admin?", username == "admin")
print("Is guest?", username == "guest")

# Store comparison results in variables
is_adult = 22 >= 18
print("\nAdult:", is_adult)

# Comparisons can be used directly in expressions
temperature = 35
print("Hot Day:", temperature > 30)