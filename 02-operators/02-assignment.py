# Assignment operators assign and update variable values.

score = 50
print("Initial Score:", score)

# Basic assignment
score = 80
print("After Assignment:", score)

# Add and assign
score += 10
print("After += :", score)

# Subtract and assign
score -= 20
print("After -= :", score)

# Multiply and assign
score *= 2
print("After *= :", score)

# Divide and assign
score /= 5
print("After /= :", score)

# Floor divide and assign
number = 17
number //= 3
print("\nAfter //= :", number)

# Modulus and assign
number = 17
number %= 5
print("After %= :", number)

# Exponent and assign
number = 3
number **= 4
print("After **= :", number)