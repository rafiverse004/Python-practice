# Arithmetic operators are used to perform mathematical calculations.

num1 = 15
num2 = 4

# Basic arithmetic operations
print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2)

# Floor division returns the integer part of the quotient
print("Floor Division:", num1 // num2)

# Modulus returns the remainder
print("Modulus:", num1 % num2)

# Exponentiation raises a number to a power
print("Exponentiation:", num1 ** num2)

# Arithmetic operators also work with variables
length = 8
width = 5
area = length * width

print("\nArea of Rectangle:", area)

# Operator precedence follows mathematical rules
result = 10 + 2 * 3
print("\n10 + 2 * 3 =", result)

# Parentheses change the evaluation order
result = (10 + 2) * 3
print("(10 + 2) * 3 =", result)

# Arithmetic with floating-point numbers
price = 99.99
tax = 5.50

total = price + tax
print("\nTotal Price:", total)