# Python has several built-in data types.

name = "Rafik"
age = 21
cgpa = 3.85
is_student = True

print(name, type(name))
print(age, type(age))
print(cgpa, type(cgpa))
print(is_student, type(is_student))

# Complex numbers are also supported.

number = 2 + 3j

print(number)
print(type(number))

# None represents the absence of a value.

result = None

print(result)
print(type(result))