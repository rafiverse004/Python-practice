# Variables are used to store data.

name = "Rafik"
age = 21
cgpa = 3.85
is_student = True

print(name)
print(age)
print(cgpa)
print(is_student)

# Python allows changing the value of a variable.

age = 22
print(age)

# Multiple variables can be assigned in one line.

x, y, z = 10, 20, 30

print(x)
print(y)
print(z)

# Multiple variables can have the same value.

a = b = c = 100

print(a)
print(b)
print(c)