# The math module provides mathematical functions and constants.

import math

number = 16

# Square root
print(f"Square root: {math.sqrt(number)}")

# Power
print(f"2 raised to 5: {math.pow(2, 5)}")

# Constants
print(f"Pi: {math.pi}")
print(f"Euler's Number: {math.e}")

# Rounding
value = 8.7

print(f"Ceiling: {math.ceil(value)}")
print(f"Floor: {math.floor(value)}")

# Trigonometric function
angle = math.radians(90)

print(f"sin(90°): {math.sin(angle)}")